"""
    get_l1_cache_bytes() -> Int

Probe the host machine's L1 data cache size in bytes.
Falls back to 32 KB if detection fails.
"""
function get_l1_cache_bytes()::Int
    # Linux: sysfs (index0 is usually L1d)
    path = "/sys/devices/system/cpu/cpu0/cache/index0/size"
    if isfile(path)
        raw = strip(read(path, String))
        raw[end] == 'K' && return parse(Int, raw[1:end-1]) * 1024
        raw[end] == 'M' && return parse(Int, raw[1:end-1]) * 1024^2
        return parse(Int, raw)
    end

    # macOS: sysctl
    try
        out = readchomp(`sysctl -n hw.l1dcachesize`)   # already in bytes
        return parse(Int, out)
    catch
    end

    @warn "PureFFT: could not detect L1 cache size, assuming 32 KB."
    return 32 * 1024
end

"""
    viable_codelet_sizes(; dtype, headroom) -> Vector{Int}

Return power-of-2 DFT sizes whose working set (input + output + twiddles)
fits within `headroom` fraction of the L1 cache. Sizes 1, 2, 4 are always
excluded because they are hand-written.
"""
function viable_codelet_sizes(; dtype::Type=ComplexF64, headroom::Float64=0.5)::Vector{Int}
    l1 = get_l1_cache_bytes()
    budget = floor(Int, l1 * headroom)
    bpe = sizeof(dtype)          # bytes per element (16 for ComplexF64)
    sizes = Int[]
    for k in 3:10                    # 8 .. 1024; skip 1/2/4 (hand-written)
        N = 2^k
        mem = N * bpe * 3            # input array + output array + twiddle table
        mem > budget && break
        push!(sizes, N)
    end
    return sizes
end

# ── Code generation ───────────────────────────────────────────────────────────

"""
    generate_codelet(N) -> String

Emit a fully unrolled `dft_N` function with all twiddle factors baked in as
literal ComplexF64 constants.  Inverse is handled at runtime via `conj`.
"""
function generate_codelet(N::Int)::String
    buf = IOBuffer()

    println(buf, "function dft_$(N)(x::AbstractArray, args...; NN::Int=$(N), inverse::Bool=false, normalize::Bool=false)")
    println(buf, "    @assert length(x) == $(N) \"dft_$(N) requires a $(N)-element array\"")

    for k in 0:N-1
        terms = String[]
        for n in 0:N-1
            # compute the forward twiddle using the package convention so signs/conj match
            index = (k * n) % N
            w = twiddle(-1, index, N)   # forward twiddle (inverse=false) convention
            wr = real(w)
            wi = imag(w)
            # Build a compact literal, skipping zero parts
            coeff = if abs(wi) < 1e-14
                repr(wr)
            elseif abs(wr) < 1e-14
                "($(repr(wi))im)"
            else
                "($(repr(wr)) + $(repr(wi))im)"
            end
            push!(terms, "x[$(n+1)] * (inverse ? conj($coeff) : $coeff)")
        end
        # Break long sums across lines for readability
        sep = " +\n             "
        println(buf, "    X_$(k) = " * join(terms, sep))
    end

    out_elems = join(["X_$k" for k in 0:N-1], ", ")
    println(buf, "    ret = [$(out_elems)]")
    println(buf, "    normalize && (ret ./= $(N))")
    println(buf, "    return ret")
    println(buf, "end")

    return String(take!(buf))
end

# ── File generation ───────────────────────────────────────────────────────────

const TUNED_FILE = joinpath(@__DIR__, "generated", "tuned_codelets.jl")

"""
    generate_tuned_codelets(; dtype, headroom, force) -> Vector{Int}

Write `src/tuned_codelets.jl` containing:
- One `dft_N` function per viable size
- `TUNED_CODELET_MAP`  — Dict used by both planners
- `TUNED_CODELET_SIZES` — sorted largest-first for `plan_fft_max`
"""
function generate_tuned_codelets(; dtype::Type=ComplexF64, headroom::Float64=0.5, limit::Int=typemax(Int))::Vector{Int}
    cpu_model = Sys.cpu_info()[1].model # e.g. "Apple M4"
    sizes = viable_codelet_sizes(; dtype, headroom)
    sizes = filter(n -> n <= limit, sizes)

    l1_kb = get_l1_cache_bytes() ÷ 1024
    @info "PureFFT.retune: CPU=$(cpu_model) with L1=$(l1_kb) KB → generating codelets for sizes $(sizes)"

    buf = IOBuffer()
    println(buf, "# AUTO-GENERATED by PureFFT.retune() — do not edit manually")
    println(buf, "# L1: $(l1_kb) KB  |  sizes: $(sizes)")
    println(buf)


    for N in sizes
        println(buf, generate_codelet(N))
        println
    end

    # CODELET_MAP covers all sizes including the hand-written ones
    all_sizes = sort(unique([1, 2, 4, sizes...]))
    fn_names = [n <= 4 ? "dft_$(n)" : "dft_$(n)" for n in all_sizes]
    map_entries = join(["$(all_sizes[i]) => $(fn_names[i])" for i in eachindex(all_sizes)], ",\n    ")
    println(buf, "const TUNED_CODELET_MAP = Dict{Int,Function}(")
    println(buf, "    $(map_entries)")
    println(buf, ")")
    println(buf)

    sorted_sizes = sort([1, 2, 4, sizes...], rev=true)
    println(buf, "const TUNED_CODELET_SIZES = $(sorted_sizes)")

    println(buf, "const TUNED_CPU = \"$(cpu_model)\"")

    write(TUNED_FILE, String(take!(buf)))
    @info "PureFFT.retune: written to $(TUNED_FILE)"
    return sizes
end

# ── Public entry point ────────────────────────────────────────────────────────

"""
    retune(; reload, dtype, headroom)

Re-detect L1 cache, regenerate machine-tuned codelets, and (optionally)
reload them into the running session.

Call this after:
- Moving the package to a new machine
- Adding new hand-written codelet sizes
- Changing the element type

```julia
PureFFT.retune()          # generate + reload in current session
PureFFT.retune(reload=false)  # generate only (used by deps/build.jl)
```
"""
function retune(; reload::Bool=true, dtype::Type=ComplexF64, headroom::Float64=0.5, limit::Int=typemax(Int))
    sizes = generate_tuned_codelets(; dtype, headroom, limit)
    if reload
        include(TUNED_FILE)
        # Merge newly loaded map into the live CODELET_MAP
        merge!(CODELET_MAP, TUNED_CODELET_MAP)
        @info "PureFFT.retune: session updated, codelet sizes now $(sort(collect(keys(CODELET_MAP)), rev=true))"
    end
    return sizes
end